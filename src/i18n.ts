const EN_PT: Record<string, string> = {};
Object.keys(PT_EN).forEach((k) => { if (!(PT_EN[k] in EN_PT)) EN_PT[PT_EN[k]] = k; });

function walk(node: Node, dict: Record<string, string>) {
  node.childNodes.forEach((n) => {
    if (n.nodeType === 3) {
      const raw = n.textContent || "";
      const t = raw.trim();
      if (t && dict[t]) n.textContent = raw.replace(t, dict[t]);
    } else if (n.nodeType === 1) {
      const tag = (n as Element).tagName;
      if (tag !== "SCRIPT" && tag !== "STYLE") walk(n, dict);
    }
  });
}
function placeholders(dict: Record<string, string>) {
  document.querySelectorAll("input[placeholder], textarea[placeholder]").forEach((el) => {
    const t = (el.getAttribute("placeholder") || "").trim();
    if (dict[t]) el.setAttribute("placeholder", dict[t]);
  });
  document.querySelectorAll("option").forEach((o) => {
    const t = (o.textContent || "").trim();
    if (dict[t]) o.textContent = dict[t];
  });
}

/* Traduz o documento. O React renderiza em PT; chamamos applyLang('en') para PT→EN.
   Para voltar ao PT, o App remonta o <main key={lang}>. */
export function applyLang(lang: "pt" | "en") {
  const dict = lang === "en" ? PT_EN : EN_PT;
  walk(document.body, dict);
  placeholders(dict);
}
